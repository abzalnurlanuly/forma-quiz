const normalize = (value) => value.replace(/\s+/gu, " ").trim();
const dictionary = new Map(
  Object.entries(kk).map(([key, value]) => [normalize(key), value]),
);
const placeholder = /\{([a-zA-Z][a-zA-Z0-9_]*)\}/gu;
const escapeRegExp = (value) => value.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&");
const signature = (value) => value.replace(placeholder, "{}");
const templateLookup = new Map();
for (const [key, translated] of dictionary) {
  if (!/\{[a-zA-Z]/u.test(key)) continue;
  templateLookup.set(signature(key), {
    names: [...key.matchAll(placeholder)].map((match) => match[1]),
    translated,
  });
}

// Anchored UI templates also handle already-rendered dynamic labels. They are
// deliberately limited to known dictionary sentences, never arbitrary prose.
const patterns = [...dictionary]
  .filter(([key]) => /\{[a-zA-Z]/u.test(key))
  .map(([key, translated]) => {
    const names = [];
    const segments = key.split(/(\{[a-zA-Z][a-zA-Z0-9_]*\})/gu);
    const expression = segments
      .map((segment) => {
        if (/^\{[a-zA-Z][a-zA-Z0-9_]*\}$/u.test(segment)) {
          names.push(segment.slice(1, -1));
          const name = segment.slice(1, -1);
          if (
            ["count", "number", "score", "max", "total", "minutes"].includes(
              name,
            )
          )
            return "([+-]?\\d+(?:[.,]\\d+)?)";
          if (name === "time") return "([\\d:]+)";
          return "(.+?)";
        }
        return escapeRegExp(segment);
      })
      .join("");
    return {
      expression: new RegExp(`^${expression}$`, "u"),
      names,
      translated,
    };
  });

function interpolate(text, values) {
  return text.replace(placeholder, (match, name) =>
    Object.prototype.hasOwnProperty.call(values, name)
      ? String(values[name] ?? "")
      : match,
  );
}

/**
 * Translate a Russian UI source key. Russian and unknown keys keep their source
 * text exactly; whitespace is normalized only for dictionary/pattern lookup.
 * Named interpolation values are inserted literally and are never translated.
 */
export function translate(text, language = "ru", values = {}) {
  const source = text == null ? "" : String(text);
  const substitutions = values && typeof values === "object" ? values : {};
  if (detectLanguage([language]) !== "kk")
    return interpolate(source, substitutions);
  const key = normalize(source);
  if (dictionary.has(key))
    return interpolate(dictionary.get(key), substitutions);
  // AST-generated value0/value1 placeholders and explicit semantic names are
  // equivalent when the surrounding Russian UI source text is the same.
  if (/\{[a-zA-Z]/u.test(key)) {
    const template = templateLookup.get(signature(key));
    if (template) {
      const sourceNames = [...key.matchAll(placeholder)].map(
        (match) => match[1],
      );
      const renamed = Object.fromEntries(
        template.names.map((name, index) => [
          name,
          Object.prototype.hasOwnProperty.call(
            substitutions,
            sourceNames[index],
          )
            ? substitutions[sourceNames[index]]
            : `{${sourceNames[index]}}`,
        ]),
      );
      return interpolate(template.translated, renamed);
    }
  }
  for (const pattern of patterns) {
    const match = pattern.expression.exec(key);
    if (!match) continue;
    const captured = Object.fromEntries(
      pattern.names.map((name, index) => [name, match[index + 1]]),
    );
    // This particular label contains a status that is itself a fixed UI key.
    if (captured.status && dictionary.has(normalize(captured.status)))
      captured.status = dictionary.get(normalize(captured.status));
    return interpolate(pattern.translated, { ...captured, ...substitutions });
  }
  return interpolate(source, substitutions);
}
