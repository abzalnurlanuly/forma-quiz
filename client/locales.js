/** Pure language detection, independent of browser globals and storage. */
export function detectLanguage(languages = []) {
  const candidates = Array.isArray(languages) ? languages : [languages];
  for (const candidate of candidates) {
    if (typeof candidate !== "string") continue;
    const code = candidate.trim().toLowerCase().split(/[-_]/u)[0];
    if (code === "ru" || code === "kk") return code;
  }
  return "ru";
}

